#!/usr/bin/env bash
# Zero-token client status check. Calls GET /api/status/clients with the
# read-only login (Q_READONLY_EMAIL / Q_READONLY_PASSWORD from the repo .env)
# and prints one compact table. With --write it also saves the snapshot note
# used by every bot room. Credentials are never printed.
#
#   scripts/client-status.sh            print table
#   scripts/client-status.sh --write    print table + write the Vault snapshot
#   BASE_URL=http://localhost:3999 scripts/client-status.sh   (local testing)
set -euo pipefail

REPO="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
BASE_URL="${BASE_URL:-https://hypheningmedia.com}"
SNAPSHOT="${SNAPSHOT:-/Volumes/Mac Valhalla/Vault/Companies/Hyphening/Docs/Hyphening - Client Status.md}"

set -a; . "$REPO/.env"; set +a
: "${Q_READONLY_EMAIL:?Q_READONLY_EMAIL missing in .env}"
: "${Q_READONLY_PASSWORD:?Q_READONLY_PASSWORD missing in .env}"

JAR="$(mktemp)"; OUT="$(mktemp)"; trap 'rm -f "$JAR" "$OUT"' EXIT

curl -sf -c "$JAR" -H 'Content-Type: application/json' \
  -d "$(python3 -c 'import json,os;print(json.dumps({"email":os.environ["Q_READONLY_EMAIL"],"password":os.environ["Q_READONLY_PASSWORD"]}))')" \
  "$BASE_URL/api/auth/login" >/dev/null || { echo "login failed at $BASE_URL" >&2; exit 1; }
curl -sf -b "$JAR" "$BASE_URL/api/status/clients" >"$OUT" \
  || { echo "GET /api/status/clients failed (endpoint not deployed yet?)" >&2; exit 1; }

python3 -I - "$OUT" "$BASE_URL" "${1:-}" "$SNAPSHOT" <<'PY'
import json, sys
path, base, mode, snap = sys.argv[1:5]
d = json.load(open(path))
onoff = lambda v: "ON" if v else "off"
rows = [("id","name","active","blog","seo","ads","gsc_property","ga4_property_id")]
for c in d["clients"]:
    rows.append((str(c["id"]), c["name"], "yes" if c["is_active"] else "no",
                 onoff(c["blog_enabled"]), onoff(c["seo_enabled"]), onoff(c["ads_enabled"]),
                 c["gsc_property"] or "unknown", c["ga4_property_id"] or "unknown"))
w = [max(len(r[i]) for r in rows) for i in range(len(rows[0]))]
line = lambda r: "| " + " | ".join(r[i].ljust(w[i]) for i in range(len(r))) + " |"
table = [line(rows[0]), "|" + "|".join("-"*(x+2) for x in w) + "|"] + [line(r) for r in rows[1:]]
print(f"generated_at: {d['generated_at']}  source: {base}")
print("\n".join(table))
if mode == "--write":
    open(snap, "w").write(f"""---
type: status-snapshot
company: "Hyphening"
generated_at: {d['generated_at']}
source: {base}/api/status/clients
---
# Hyphening: client status snapshot

**generated_at: {d['generated_at']}** (auto-generated by `scripts/client-status.sh --write`; do not hand-edit). Rules: [[Companies/Hyphening/Docs/Hyphening - Client Status Protocol]].

{chr(10).join(table)}
""")
    print("wrote", snap)
PY
